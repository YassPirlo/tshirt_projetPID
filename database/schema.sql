-- Base de donnees du projet TshirtShop (US1 a US3)
-- A executer dans phpMyAdmin (onglet SQL) en etant connecte en root.
-- Attention : le script supprime et recree les tables.

CREATE DATABASE IF NOT EXISTS tshirt_shop CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE USER IF NOT EXISTS 'tshirt_user'@'localhost' IDENTIFIED BY 'tshirt123';
GRANT ALL PRIVILEGES ON tshirt_shop.* TO 'tshirt_user'@'localhost';
FLUSH PRIVILEGES;

USE tshirt_shop;

-- Moteur InnoDB impose sur chaque table, quel que soit le reglage par
-- defaut du MySQL de chacun. Avec MyISAM (ancien moteur, encore par defaut
-- sur certaines installations), la creation de la table utilisateur
-- echoue : l'index UNIQUE de l'email (255 caracteres x 4 octets en utf8mb4
-- = 1020 octets) depasse sa limite de 1000 octets. MyISAM ignore aussi
-- les cles etrangeres.
DROP TABLE IF EXISTS utilisateur;
DROP TABLE IF EXISTS localite;
DROP TABLE IF EXISTS produit;
DROP TABLE IF EXISTS marque;
DROP TABLE IF EXISTS categorie;

-- Comptes clients (US4 a US7 : inscription, connexion, deconnexion, profil)
CREATE TABLE utilisateur (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  -- UNIQUE : la base refuse deux comptes avec la meme adresse
  email VARCHAR(255) NOT NULL UNIQUE,
  -- Jamais le mot de passe en clair : on stocke un hachage BCrypt,
  -- qui fait toujours exactement 60 caracteres.
  mot_de_passe VARCHAR(60) NOT NULL,
  nom VARCHAR(100) NOT NULL,
  prenom VARCHAR(100) NOT NULL,
  -- US5 : adresse demandee a l'inscription. code_postal en texte : ce
  -- n'est pas un nombre (pas de calcul, lettres possibles a l'etranger).
  adresse VARCHAR(255) NOT NULL,
  code_postal VARCHAR(10) NOT NULL,
  ville VARCHAR(100) NOT NULL,
  -- Code pays ISO a deux lettres. Seule la Belgique (BE) est disponible
  -- pour l'instant : code postal et ville sont verifies avec la table
  -- localite ci-dessous.
  pays VARCHAR(2) NOT NULL,
  date_inscription DATETIME NOT NULL,
  -- Date a laquelle le client a accepte les conditions generales de vente
  -- (case obligatoire a l'inscription) : preuve de son accord.
  cgv_acceptees_le DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Localites belges : liste officielle bpost des codes postaux
-- (zipcodes_num_fr_2025.xls, bpost.be). Sert a verifier qu'un code postal
-- existe et que la ville lui correspond (inscription, profil).
-- Un code peut couvrir plusieurs localites (4000 : Glain, Liege, Rocourt).
-- Les communes de Bruxelles y figurent en neerlandais ; leur nom francais
-- officiel a ete ajoute (1000 : Brussel et Bruxelles).
-- Les codes speciaux sans province (institutions, entreprises) sont exclus.
CREATE TABLE localite (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  code_postal VARCHAR(4) NOT NULL,
  nom VARCHAR(100) NOT NULL,
  province VARCHAR(50) NOT NULL,
  INDEX idx_localite_code_postal (code_postal)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE categorie (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  nom VARCHAR(100) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE marque (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  nom VARCHAR(100) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE produit (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  nom VARCHAR(100) NOT NULL,
  prix DECIMAL(10, 2) NOT NULL,
  image_url VARCHAR(500),
  description VARCHAR(1000),
  matiere VARCHAR(255),
  entretien VARCHAR(255),
  categorie_id BIGINT NOT NULL,
  marque_id BIGINT NOT NULL,
  FOREIGN KEY (categorie_id) REFERENCES categorie(id),
  FOREIGN KEY (marque_id) REFERENCES marque(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

